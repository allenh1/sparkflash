"""Regenerate tests/fixtures/v41_flash_tensor_digest.txt from the released checkpoint index.

The engine crate derives the 95,819 language-model tensor names from the configuration rather than
from the index, which is the point - a derived plan can disagree with the checkpoint and the
disagreement is the interesting event. But the index is a 7.4 MB file that is not in this repository
and not on a CI runner, so without a committed artefact the central claim is never checked in CI.
This script reduces the index to a digest, and tests/tensor_plan.rs checks the plan against that
digest on every run.

Usage: python3 scripts/regen-tensor-fixture.py [path/to/model.safetensors.index.json]
"""
import collections
import hashlib
import json
import pathlib
import sys

FNV_OFFSET = 0xCBF29CE484222325
FNV_PRIME = 0x100000001B3
MASK = (1 << 64) - 1


def fnv1a64(names):
    """FNV-1a 64 over the sorted names joined by a newline, matching synthetic::fnv1a."""
    h = FNV_OFFSET
    for byte in "\n".join(sorted(names)).encode():
        h ^= byte
        h = (h * FNV_PRIME) & MASK
    return h


def main():
    default = pathlib.Path("/home/user/dsv41-research/model.safetensors.index.json")
    path = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else default
    raw = path.read_bytes()
    index = json.loads(raw)
    names = sorted(index["weight_map"])
    total_size = index["metadata"]["total_size"]

    vision = [n for n in names if n.startswith("vision.")]
    aligner = [n for n in names if n.startswith("aligner.")]
    image = [n for n in names if n.startswith("image_")]
    layers = [n for n in names if n.startswith("layers.")]
    mtp = [n for n in names if n.startswith("mtp.")]
    globals_ = [n for n in names if not n.startswith(("vision.", "aligner.", "image_", "layers.", "mtp."))]
    excluded = vision + aligner + image
    lm = layers + mtp + globals_

    assert len(excluded) + len(lm) == len(names), "every name must be classified"
    assert not set(excluded) & set(lm), "and classified exactly once"

    out = pathlib.Path(__file__).resolve().parent.parent / "tests/fixtures/v41_flash_tensor_digest.txt"
    lines = [
        "# Generated by scripts/regen-tensor-fixture.py - do not edit by hand.",
        f"# source {path}",
        f"source_bytes {len(raw)}",
        f"index_sha256 {hashlib.sha256(raw).hexdigest()}",
        f"total_tensors {len(names)}",
        f"language_model {len(lm)}",
        f"layers {len(layers)}",
        f"mtp {len(mtp)}",
        f"globals {len(globals_)}",
        f"excluded {len(excluded)}",
        f"vision {len(vision)}",
        f"aligner {len(aligner)}",
        f"image_delimiters {len(image)}",
        f"metadata_total_size {total_size}",
        f"plan_names_fnv1a64 {fnv1a64(lm):016x}",
    ]
    out.write_text("\n".join(lines) + "\n")
    print("\n".join(lines))
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
