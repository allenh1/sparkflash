/// Odd lookback multipliers, `MULTIPLIERS[layer][lookback]` for lookback 0..=3 (shift 0 is
/// the token itself, shift 3 the 4-gram's oldest token).
///
/// Generated by numpy as described in the module docs; `MULTIPLIERS[0]` belongs to backbone
/// layer 1 and `MULTIPLIERS[1]` to backbone layer 14.
///
/// Each entry is `2 * drawn + 1` with `drawn < multiplier_bound()`, so a multiplier is odd
/// and lies in `[1, multiplier_ceiling()]` - it is *not* itself below `multiplier_bound()`.
/// The invariant that matters is that `token_id * multiplier` cannot overflow `i64`, which
/// `multiplier_ceiling()` and [`multiplier_bound`] establish.
///
/// Provenance caveat: the numpy PCG64 draw is **not** reproduced in Rust, so these pins are
/// only ever checked externally, by `tests/engram_hash.rs` hashing with the reference's own
/// multipliers from `tests/fixtures/hash/hash_cases.json`.
/// `golden_multiplier_constants_are_pinned` in `tests/prime_layout.rs` merely guards
/// against accidental edits and must not be mistaken for an independent derivation.
