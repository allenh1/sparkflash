/// Upper bound (exclusive) used when the multipliers were drawn:
/// `max(1, (i64::MAX / COMPRESSED_VOCAB_SIZE) / 2)` = 46,539,438,283,891.
///
/// The bound exists so that `token_id * multiplier` cannot overflow `i64`: the largest
/// compressed id is `COMPRESSED_VOCAB_SIZE - 1`, the largest multiplier is `2 * bound - 1`,
/// and `2 * bound <= i64::MAX / COMPRESSED_VOCAB_SIZE`.
#[must_use]
pub const fn multiplier_bound() -> u64 {
    let bound = (i64::MAX as u64) / COMPRESSED_VOCAB_SIZE as u64 / 2;
    if bound > 1 { bound } else { 1 }
}

/// Largest multiplier that can result from the documented derivation, `2 * bound - 1`.
///
/// The reference draws `values < multiplier_bound()` and stores `2 * values + 1`, so the
/// multipliers themselves live in `[1, multiplier_ceiling()]`.
#[must_use]
pub const fn multiplier_ceiling() -> u64 {
    2 * multiplier_bound() - 1
}

/// Number of rows in one layer's table, `ENGRAM_NUM_EMBEDDINGS[layer_index]`.
///
/// # Panics
/// Panics when `layer_index` is not a valid Engram layer index (0 or 1).
#[must_use]
pub const fn layer_rows(layer_index: usize) -> u64 {
    ENGRAM_NUM_EMBEDDINGS[layer_index]
}

/// Flat column index `24 * order_index + head` of one (order, head) bucket.
///
/// # Panics
/// Panics when `order_index >= 3` or `head >= 8`; these are compile-time constants in
/// practice, so the bounds are checked once here rather than at every lookup.
#[must_use]
pub const fn column_index(order_index: usize, head: usize) -> usize {
    assert!(order_index < 3, "n-gram order index out of range");
    assert!(head < 8, "hash head out of range");
    order_index * 8 + head
}

/// Table row offset of one (layer, order, head) bucket.
#[must_use]
pub const fn bucket_offset(layer_index: usize, order_index: usize, head: usize) -> u64 {
    OFFSETS[layer_index][column_index(order_index, head)]
}

/// Length (prime modulus) of one (layer, order, head) bucket.
#[must_use]
pub const fn bucket_len(layer_index: usize, order_index: usize, head: usize) -> u32 {
    PRIMES[layer_index][order_index][head]
}

/// Half-open row range `[start, end)` owned by one (layer, order, head) bucket.
#[must_use]
pub const fn bucket_range(
    layer_index: usize,
    order_index: usize,
    head: usize,
) -> core::ops::Range<u64> {
    let start = bucket_offset(layer_index, order_index, head);
    core::ops::Range {
        start,
        end: start + bucket_len(layer_index, order_index, head) as u64,
    }
}

/// The 48 primes of one layer in flat `24 * order + head` column order.
#[must_use]
pub const fn flat_primes(layer_index: usize) -> [u32; 24] {
    let mut flat = [0u32; 24];
    let mut order = 0;
    while order < 3 {
        let mut head = 0;
        while head < 8 {
            flat[order * 8 + head] = PRIMES[layer_index][order][head];
            head += 1;
        }
        order += 1;
    }
    flat
}
