//! Prime bucket layout of the Engram n-gram hash tables. OWNER: engram-hash.
//!
//! Every Engram layer owns one table of `ENGRAM_NUM_EMBEDDINGS[layer]` rows. That table is
//! partitioned into 24 disjoint bucket ranges: one per (n-gram order, head) pair, where the
//! orders are the 2-, 3- and 4-grams and there are 8 heads each. A range is identified by a
//! prime modulus (its length) and a cumulative offset (its start), so a hash column
//! `24*c + h` for order index `c` and head `h` indexes
//! `OFFSETS[layer][24*c + h] .. OFFSETS[layer][24*c + h] + PRIMES[layer][c][h]`.
//!
//! # Provenance
//!
//! These tables are a transcription of the released reference implementation
//! (`reference/inference/engram.py`, `EngramLayout.from_args` and
//! `compute_hash_multipliers`), cross-checked against
//! `/home/user/dsv41-research/engram_golden.json`. `tests/prime_layout.rs` does not
//! trust the transcription: it re-derives all 48 primes from scratch with its own
//! Miller-Rabin implementation and re-computes every offset, then compares against the
//! constants below.
//!
//! * `PRIMES` - 48 distinct primes, drawn in the order layer 0(order 2 heads 0..7, order 3
//!   heads 0..7, order 4 heads 0..7), then layer 1 the same way. Each draw is the smallest
//!   prime greater than `ENGRAM_VOCAB_SIZE - 1` that has not been handed out before (the
//!   reference keeps one global `seen` set), so the flat 48-entry sequence is strictly
//!   ascending. The 24 primes of a layer sum to exactly that layer's row count, which is the
//!   check that validates the draw order.
//! * `OFFSETS` - for each layer, the running sum of the preceding primes in the flat
//!   24-entry order (equivalently `np.cumsum([0, *sizes[:-1]])` over the flat primes).
//! * `MULTIPLIERS` - the four odd lookback multipliers of each layer, generated by numpy as
//!   `np.random.default_rng(10007 * layer_id).integers(low=0, high=multiplier_bound(),
//!   size=(4,), dtype=np.int64) * 2 + 1`, with `layer_id` the *backbone* layer (1 and 14,
//!   not 0 and 1). They are pinned constants because numpy's PCG64 + Lemire-bounded draw is
//!   not reproduced in Rust: these four numbers per layer are copied from the reference, and
//!   `tests/prime_layout.rs` only proves that the pinned values are odd, in range, and
//!   layer-distinct. The pins are validated *externally* by `tests/engram_hash.rs`, which
//!   hashes with the reference's own multipliers from
//!   `tests/fixtures/hash/hash_cases.json`, so `golden_multiplier_constants_are_pinned`
//!   is a guard against accidental edits rather than an independent check.

