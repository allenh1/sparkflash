    #[test]
    fn usage_block_matches_the_documented_key_set() {
        let usage = OpenAiUsageWithCache {
            prompt_tokens: 32768,
            completion_tokens: 256,
            total_tokens: 33024,
            prompt_tokens_details: PromptTokensDetails {
                cached_tokens: 28672,
                uma_cached_tokens: 28672,
                nvme_cached_tokens: 0,
                image_tokens: 0,
            },
            completion_tokens_details: CompletionTokensDetails {
                reasoning_tokens: 94,
                accepted_prediction_tokens: 212,
                rejected_prediction_tokens: 48,
            },
            prompt_cache_hit_tokens: 28672,
            prompt_cache_miss_tokens: 4096,
        };
        let json = serde_json::to_value(usage).expect("usage serializes");
        assert_eq!(
            keys(&json),
            key_set(&[
                "prompt_tokens",
                "completion_tokens",
                "total_tokens",
                "prompt_tokens_details",
                "completion_tokens_details",
                "prompt_cache_hit_tokens",
                "prompt_cache_miss_tokens",
            ])
        );
        assert_eq!(json["prompt_cache_hit_tokens"], serde_json::json!(28672));
        assert_eq!(json["prompt_cache_miss_tokens"], serde_json::json!(4096));
        assert_eq!(
            keys(&json["prompt_tokens_details"]),
            key_set(&[
                "cached_tokens",
                "uma_cached_tokens",
                "nvme_cached_tokens",
                "image_tokens"
            ])
        );
        assert_eq!(
            keys(&json["completion_tokens_details"]),
            key_set(&[
                "reasoning_tokens",
                "accepted_prediction_tokens",
                "rejected_prediction_tokens"
            ])
        );
    }

    #[test]
    fn stats_round_trip_through_json() {
        let stats = populated_stats();
        let text = serde_json::to_string(&stats).expect("stats serialize");
        let back: DeepSeekSparkRequestStats =
            serde_json::from_str(&text).expect("stats deserialize");
        assert_eq!(back, stats);
    }
