#!/bin/sh
# Writes the kernel baseline: for each baseline kernel (the forty entries: the six Milestone 4
# kernels, the M7 SwiGLU quantiser epilogue and its weighted routed variant, the task-37 device router,
# the task-8 routed gate/up GEMM, the serving tail's standalone final RMSNorm, the certified head's
# device reduce, the CSA2 sequence attention entry, D49's ring-capacity CSA2 entry and the D37
# precision-first BF16-activation projection pair, the three Engram head kernels: the embed row
# and activation quantiser, the W8A8 wkv projection, and the gate and write (task-9), and the
# stored-layout variant of the routed combine (task-6: the released plan's 288-byte code rows and
# 18-byte scale rows)), and the three S1 device-layer sources: the Engram gate and write, the
# stream dtype conversions in one cubin (f32->bf16 narrow, bf16->f32 widen) and the routed-MoE
# staging and combine pair (both by-name symbols, one pin each), the cubin bytes, the
# cubin sha256 and the number of `membar`
# lines nvcc emits in its PTX,
# under the toolkit that made them.
#
# The text this prints is what scripts/check-kernel-baseline.sh compares against
# baseline/kernel_baseline.txt, so this script is the single source of the format: run it with no
# argument to print the baseline, or with a path to write it there.
#
# Regenerate it only together with a review of the kernel change that moved a number. A baseline
# regenerated to silence a failure proves nothing: the whole point is that a change to a kernel's
# compiled form - the acquire fence disappearing, a codec constant moving - shows up as a diff.
set -eu

crate_dir=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
kernels=$(CDPATH= cd -- "$crate_dir/../../kernels" && pwd)
nvcc=${SPARKFLASH_NVCC:-nvcc}
arch=sm_121a

if ! command -v "$nvcc" >/dev/null 2>&1; then
    echo "nvcc is not on PATH: run this script on a CUDA host or inside the CUDA container" >&2
    exit 127
fi

release=$("$nvcc" --version | sed -n 's/^Cuda compilation tools, release [^,]*, \(V[^ ]*\)$/\1/p')
build=$("$nvcc" --version | sed -n 's/^Build \(.*\)$/\1/p')
if [ -z "$release" ] || [ -z "$build" ]; then
    echo "cannot read the toolkit version out of $nvcc --version" >&2
    "$nvcc" --version >&2
    exit 1
fi

work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

emit() {
    cat <<EOF
# Kernel baseline: what nvcc compiles the forty baseline kernels into (the six Milestone 4 kernels,
# the M7 SwiGLU quantiser epilogue and its weighted routed variant, the task-37 device router, the
# task-8 routed gate/up GEMM, the serving tail's standalone final RMSNorm, the certified head's
# device reduce, the CSA2 sequence attention entry, D49's ring-capacity CSA2 entry, the D37
# BF16-activation projection pair, the three Engram head kernels (task-9: embed row and activation
# quantiser, W8A8 wkv, gate and write) and the stored-layout down-projection variant of the routed
# combine (task-6: 288-byte code rows and 18-byte scale rows from the released plan)), and the
# WS-D columns-only M=1 dense projection (kernels/b12x_mxfp8_dense_m1_sm121.cu: an addition with
# its own cubin and its own symbol, so the pinned dense cubin is untouched), and the WS-D decode
# GEMV (kernels/b12x_mxfp8_gemv_m1_sm121.cu: a bandwidth-first addition with its own cubin, symbol
# and baseline entry; the pinned dense and the M=1 symbols are untouched), and the host-weight decode
# GEMV of the ref_seam slice (kernels/b12x_hostw_gemv_m1_sm121.cu: the same M=1 tiling over the
# checkpoint f32 and bf16 weights the compressor and indexer projections carry, again its own cubin,
# symbols and baseline entry, with the pinned GEMV untouched), and the three S1 device-layer
# sources (Engram gate/write, the two-direction stream dtype conversion cubin, and the routed-MoE
# staging/combine pair: all by-name symbols with one pin per cubin), and the S1 ratio>0 compressor
# pooling (kernels/pool_group_sm121.cu: the by-name pool_group_f32 symbol, no KernelId, one pin), and
# the nine opt decode sources (kernels/opt_*_sm121.cu: the M=1 and multi-row opt path, by-name
# symbols, one pin per cubin).
#
# Generated by scripts/regen-kernel-baseline.sh and verified by scripts/check-kernel-baseline.sh,
# which the Rust test tests/kernel_baseline.rs runs as well. The cubin sha256 is the compiled form of
# the kernel, ptx_membar_lines is the fence the PTX really carries, and the toolkit version is
# recorded so that a newer nvcc is reported as a toolkit change instead of as a kernel change.
nvcc_release=$release
nvcc_build=$build
arch=$arch
EOF
    for kernel in mega_mhc_sm121 b12x_mxfp8_dense_sm121 b12x_mxfp8_dense_m1_sm121 b12x_mxfp8_gemv_m1_sm121 b12x_mxfp4_moe_sm121 b12x_mxfp4_moe_stored_sm121 flash_mla_csa2_sm121 b12x_mxfp8_wo_a_sm121 cert_lm_head_sm121 swiglu_mxfp8_quant_sm121 moe_router_sm121 routed_gate_up_sm121 swiglu_mxfp8_quant_weighted_sm121 rmsnorm_sm121 lm_head_reduce_sm121 flash_mla_csa2_seq_sm121 flash_mla_csa2_ring_sm121 b12x_bf16a_mxfp8w_dense_sm121 b12x_bf16a_mxfp8w_wo_a_sm121 engram_embed_sm121 engram_wkv_sm121 engram_gate_write_sm121 b12x_hostw_gemv_m1_sm121 layer_seams_sm121 kv_path_sm121 ref_select_sm121 compressed_append_sm121 engram_write_sm121 engram_stream_convert_sm121 moe_routed_device_sm121 pool_group_sm121 opt_attn_sm121 opt_draft_sm121 opt_gemv_sm121 opt_misc_sm121 opt_moe_sm121 opt_router_sm121 opt_rows_sm121 opt_seams_sm121 opt_select_sm121; do
        "$nvcc" -std=c++17 "-arch=$arch" -cubin -I "$kernels" "$kernels/$kernel.cu" -o "$work/$kernel.cubin"
        "$nvcc" -std=c++17 "-arch=$arch" --ptx -I "$kernels" "$kernels/$kernel.cu" -o "$work/$kernel.ptx"
        bytes=$(wc -c < "$work/$kernel.cubin" | tr -d ' ')
        sha=$(sha256sum "$work/$kernel.cubin" | cut -d' ' -f1)
        membars=$(grep -c membar "$work/$kernel.ptx" || true)
        echo "kernel $kernel cubin_bytes=$bytes cubin_sha256=$sha ptx_membar_lines=$membars"
    done
}

if [ "$#" -ge 1 ]; then
    emit > "$1"
else
    emit
fi
