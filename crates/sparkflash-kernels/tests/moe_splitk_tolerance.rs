//! The D51 tolerance harness for the fused split-K routed gate/up kernel, CPU-only.
//!
//! This file is the CPU arm of the verification: it runs the reference chain and the performance
//! arm's model on deterministic pseudo-random operands at the real shapes (hidden 5120, routed
//! width 576 -> 640, six slots) and prints
//!
//! * the per-element deviation row against the bit-exact twin (max/mean absolute and relative, the
//!   bf16 ulp row, the code/scale mismatch fractions, the dequantised-operand row) - D51's
//!   per-kernel tolerance row;
//! * the traffic the launch addresses and the CPU arm's achieved GB/s against the 273 GB/s per-node
//!   floor - a HOST number, printed for the arithmetic and explicitly not a device claim. The
//!   device row (p50 ms, achieved GB/s, percentage, occupancy) is the Lead's run: its steps are
//!   crate::routed_gate_up_swiglu_splitk_abi::GPU_VERIFICATION_PLAN.
//!
//! No test here launches a kernel, opens a device or reads a cubin; a CPU-only host runs all of
//! them.

use sparkflash_kernels::m4_quant::{bf16_bits, fp8_e4m3_encode, ue8m0_decode};
use sparkflash_kernels::roofline;
use sparkflash_kernels::routed_gate_up_ref;
use sparkflash_kernels::routed_gate_up_swiglu_splitk_ref as splitk;
use sparkflash_kernels::swiglu_ref;
use std::sync::OnceLock;
use std::time::Instant;

/// The number of resident experts the synthetic table holds: more than six, so the slot gather is
/// a real gather.
const EXPERTS: usize = 8;
/// Tokens in the tolerance arm: the decode shape.
const TOKENS: usize = 1;

/// A deterministic linear-congruential generator, so the row is reproducible on any host.
struct Lcg(u64);

impl Lcg {
    fn next_u32(&mut self) -> u32 {
        self.0 = self
            .0
            .wrapping_mul(6_364_136_223_846_793_005)
            .wrapping_add(1_442_695_040_888_963_407);
        (self.0 >> 33) as u32
    }

    fn unit(&mut self) -> f32 {
        (self.next_u32() >> 8) as f32 / (1u32 << 24) as f32
    }

    fn uniform(&mut self, low: f32, high: f32) -> f32 {
        low + (high - low) * self.unit()
    }

    fn byte(&mut self) -> u8 {
        (self.next_u32() >> 24) as u8
    }

    fn below(&mut self, bound: u32) -> u32 {
        self.next_u32() % bound
    }
}

/// One deterministic operand set shared by every test in this binary.
struct Inputs {
    act_fp8: Vec<u8>,
    act_scales: Vec<u8>,
    w1_fp4: Vec<u8>,
    w1_scales: Vec<u8>,
    w3_fp4: Vec<u8>,
    w3_scales: Vec<u8>,
    expert_ids: Vec<u32>,
    routing_weights: Vec<f32>,
}

fn inputs() -> &'static Inputs {
    static INPUTS: OnceLock<Inputs> = OnceLock::new();
    INPUTS.get_or_init(|| {
        let mut rng = Lcg(0x5EED_5121_0A0B_0C0Du64);
        // E4M3 codes: generated by the encoder from a bounded f32, so every byte is a finite code.
        let act_fp8: Vec<u8> = (0..TOKENS * splitk::HIDDEN)
            .map(|_| fp8_e4m3_encode(rng.uniform(-4.0, 4.0)))
            .collect();
        // ue8m0 codes around the activation's magnitude: 2^-7 .. 2^4.
        let act_scales: Vec<u8> = (0..TOKENS * splitk::SCALE_ROW_BYTES)
            .map(|_| 120 + rng.below(12) as u8)
            .collect();
        // Weight scales 2^-9 .. 2^2.
        let weight_scales = |count: usize, rng: &mut Lcg| -> Vec<u8> {
            (0..count).map(|_| 118 + rng.below(12) as u8).collect()
        };
        let weight_bytes = EXPERTS * splitk::WIDTH * splitk::WEIGHT_ROW_BYTES;
        let scale_bytes = EXPERTS * splitk::WIDTH * splitk::SCALE_ROW_BYTES;
        let w1_fp4: Vec<u8> = (0..weight_bytes).map(|_| rng.byte()).collect();
        let w3_fp4: Vec<u8> = (0..weight_bytes).map(|_| rng.byte()).collect();
        let w1_scales = weight_scales(scale_bytes, &mut rng);
        let w3_scales = weight_scales(scale_bytes, &mut rng);
        // The routed slots: six distinct staged slice indices per token.
        let expert_ids: Vec<u32> = (0..TOKENS)
            .flat_map(|token| {
                (0..splitk::TOP_K).map(move |slot| ((slot * 5 + token) % EXPERTS) as u32)
            })
            .collect();
        let routing_weights: Vec<f32> = (0..TOKENS * splitk::TOP_K)
            .map(|_| rng.uniform(0.05, 1.0))
            .collect();
        Inputs {
            act_fp8,
            act_scales,
            w1_fp4,
            w1_scales,
            w3_fp4,
            w3_scales,
            expert_ids,
            routing_weights,
        }
    })
}

/// The reference arm on the shared inputs.
fn reference(inputs: &Inputs) -> splitk::TwinOutput {
    splitk::twin_activation(
        &inputs.act_fp8,
        &inputs.act_scales,
        &inputs.w1_fp4,
        &inputs.w1_scales,
        &inputs.w3_fp4,
        &inputs.w3_scales,
        &inputs.expert_ids,
        &inputs.routing_weights,
        TOKENS,
        EXPERTS,
    )
}

/// The performance arm on the shared inputs.
fn performance(inputs: &Inputs) -> splitk::SplitKOutput {
    splitk::splitk_activation(
        &inputs.act_fp8,
        &inputs.act_scales,
        &inputs.w1_fp4,
        &inputs.w1_scales,
        &inputs.w3_fp4,
        &inputs.w3_scales,
        &inputs.expert_ids,
        &inputs.routing_weights,
        TOKENS,
        EXPERTS,
        splitk::SWIGLU_LIMIT,
    )
}

/// The block terms this module folds must be the pinned twin's arithmetic.
///
/// The tolerance row is only meaningful if the performance arm differs from the reference in the
/// reduction ORDER alone, so this pins the arm's shared block term to
/// [routed_gate_up_ref::gate_up]'s output on the same operands: folding the 160 terms serially and
/// rounding once reproduces the pinned kernel's bf16 byte for the sampled elements.
#[test]
fn the_serial_fold_reproduces_the_pinned_reference_bytes() {
    let inputs = inputs();
    let (gate_bf16, _) = routed_gate_up_ref::gate_up(
        &inputs.act_fp8,
        &inputs.act_scales,
        &inputs.w1_fp4,
        &inputs.w1_scales,
        &inputs.expert_ids,
        TOKENS,
        EXPERTS,
    );
    let (up_bf16, _) = routed_gate_up_ref::gate_up(
        &inputs.act_fp8,
        &inputs.act_scales,
        &inputs.w3_fp4,
        &inputs.w3_scales,
        &inputs.expert_ids,
        TOKENS,
        EXPERTS,
    );
    let mut checked = 0usize;
    for row in 0..TOKENS * splitk::TOP_K {
        let token = row / splitk::TOP_K;
        let act_row = &inputs.act_fp8[token * splitk::HIDDEN..][..splitk::HIDDEN];
        let act_scale_row =
            &inputs.act_scales[token * splitk::SCALE_ROW_BYTES..][..splitk::SCALE_ROW_BYTES];
        let expert = inputs.expert_ids[row] as usize;
        // Sample columns across the width, including both block boundaries and the last column.
        for column in [0usize, 1, 31, 32, 255, 575] {
            let weight_row = expert * splitk::WIDTH + column;
            let w1_row =
                &inputs.w1_fp4[weight_row * splitk::WEIGHT_ROW_BYTES..][..splitk::WEIGHT_ROW_BYTES];
            let s1_row = &inputs.w1_scales[weight_row * splitk::SCALE_ROW_BYTES..]
                [..splitk::SCALE_ROW_BYTES];
            let w3_row =
                &inputs.w3_fp4[weight_row * splitk::WEIGHT_ROW_BYTES..][..splitk::WEIGHT_ROW_BYTES];
            let s3_row = &inputs.w3_scales[weight_row * splitk::SCALE_ROW_BYTES..]
                [..splitk::SCALE_ROW_BYTES];
            let gate =
                splitk::serial_fold(&splitk::block_terms(act_row, act_scale_row, w1_row, s1_row));
            let up =
                splitk::serial_fold(&splitk::block_terms(act_row, act_scale_row, w3_row, s3_row));
            assert_eq!(
                bf16_bits(gate),
                gate_bf16[row * splitk::WIDTH_PADDED + column],
                "row {row} column {column}: the serial fold must be the pinned gate/up arithmetic"
            );
            assert_eq!(
                bf16_bits(up),
                up_bf16[row * splitk::WIDTH_PADDED + column],
                "row {row} column {column}: the serial fold must be the pinned gate/up arithmetic"
            );
            checked += 2;
        }
    }
    assert_eq!(checked, TOKENS * splitk::TOP_K * 12);
}

/// The two folds are the documented expressions and are not the same expression.
///
/// Hand-built terms make the orders visible: the serial fold is a 160-add chain, the split-K fold
/// is eight 20-term shard sums combined as `((t0+t1)+(t2+t3))+((t4+t5)+(t6+t7))`. With terms that
/// cancel in different places the two disagree in the last bits, which is exactly what D51's
/// tolerance row is there to bound.
#[test]
fn the_splitk_fold_is_the_documented_butterfly() {
    let mut terms = [0.0f32; splitk::K_BLOCKS];
    for (block, term) in terms.iter_mut().enumerate() {
        // Alternating magnitudes: the first and last blocks dominate, the middle cancels.
        let sign = if block.is_multiple_of(2) { 1.0 } else { -1.0 };
        *term = sign * (1.0 + block as f32 * 1.0e-3);
    }
    let mut shard = [0.0f32; splitk::WARPS];
    for (s, total) in shard.iter_mut().enumerate() {
        *total = splitk::splitk_shard_fold(&terms, s);
        // And the shard fold is the ascending `s + 8*j` chain.
        let mut expected = 0.0f32;
        for j in 0..splitk::BLOCKS_PER_SHARD {
            expected += terms[s + splitk::WARPS * j];
        }
        assert_eq!(total.to_bits(), expected.to_bits(), "shard {s}");
    }
    let expected = ((shard[0] + shard[1]) + (shard[2] + shard[3]))
        + ((shard[4] + shard[5]) + (shard[6] + shard[7]));
    assert_eq!(splitk::splitk_fold(&terms).to_bits(), expected.to_bits());
    assert_ne!(
        splitk::splitk_fold(&terms).to_bits(),
        splitk::serial_fold(&terms).to_bits(),
        "the reassociation must be visible on adversarial terms"
    );
}

/// The fused epilogue's per-element map is the reference's.
#[test]
fn the_weighted_epilogue_is_the_reference_map() {
    let mut rng = Lcg(0xA11CE);
    for _ in 0..64 {
        let gate = rng.uniform(-12.0, 12.0);
        let up = rng.uniform(-12.0, 12.0);
        let weight = rng.uniform(0.01, 1.0);
        let reference =
            swiglu_ref::weighted_activation(&[gate], &[up], splitk::SWIGLU_LIMIT, weight);
        assert_eq!(
            splitk::weighted_value(gate, up, splitk::SWIGLU_LIMIT, weight).to_bits(),
            reference[0].to_bits(),
            "gate {gate} up {up} weight {weight}"
        );
    }
}

/// The D51 tolerance row, the host throughput row and the traffic arithmetic.
///
/// The assertions are the declared bounds; the printed lines are the record. The GB/s line is the
/// CPU arm's, labelled as such: the device row is the Lead's run.
#[test]
fn the_tolerance_row_is_within_the_declared_bounds_and_is_recorded() {
    let inputs = inputs();
    let twin = reference(inputs);
    // The CPU arm's wall clock is taken around the one performance-arm run this row uses; the
    // number is a host ratio, printed below, not a device measurement.
    let start = Instant::now();
    let split = performance(inputs);
    let host_ms = start.elapsed().as_secs_f64() * 1.0e3;
    let row = splitk::deviation(&twin, &split);
    println!("{}", splitk::summary(&row));
    assert_eq!(
        row.live_elements,
        TOKENS * splitk::TOP_K * splitk::WIDTH * 2,
        "every live element of both projections is compared"
    );
    assert_eq!(row.padding_mismatches, 0, "the zero tail is bit-identical");
    assert!(
        row.f32_max_abs > 0.0,
        "the rows must actually differ in the f32 accumulator, or the tolerance row is vacuous"
    );
    if let Err(failure) = splitk::DECLARED_TOLERANCE.check(&row) {
        panic!(
            "the D51 tolerance row failed: {failure}\n{}",
            splitk::summary(&row)
        );
    }
    assert_eq!(
        split.macs,
        (TOKENS * splitk::TOP_K * splitk::WIDTH * 2 * splitk::HIDDEN) as u64
    );

    // The traffic the launch addresses, and what the fusion removes.
    assert_eq!(split.traffic.intermediate_bytes, 0);
    assert!(twin.traffic.intermediate_bytes > 0);
    assert_eq!(
        split.traffic.weight_bytes,
        (TOKENS * splitk::TOP_K * splitk::WIDTH * splitk::WEIGHT_ROW_BYTES * 2) as u64
    );
    assert!(
        split.traffic.total() < twin.traffic.total(),
        "the fusion must address fewer bytes: fused {} vs chain {}",
        split.traffic.total(),
        twin.traffic.total()
    );

    // The host arm's throughput: a labelled CPU number, never a device claim.
    let bytes = split.traffic.total();
    let host_gbs = roofline::achieved_gbs(bytes, host_ms);
    println!(
        "roofline: kernel=routed_gate_up_swiglu_splitk host_reference_arm=1 traffic_bytes={bytes} \
         host_ms={host_ms:.3} host_achieved_gbs={host_gbs:.2} node_gbs={:.1} \
         host_pct_of_node={:.2}% device_floor_us_at_node_gbs={:.1} \
         (a CPU arm ratio for the arithmetic; the device row is the GPU verification plan)",
        roofline::NODE_GBPS,
        roofline::percent_of_node(host_gbs),
        bytes as f64 / (roofline::NODE_GBPS * 1.0e9) * 1.0e6,
    );
    println!(
        "traffic_compare: fused_bytes={} chain_bytes={} removed_intermediate_bytes={} \
         activation_reads=1_vs_2",
        split.traffic.total(),
        twin.traffic.total(),
        twin.traffic.intermediate_bytes,
    );
    assert!(host_gbs.is_finite() && host_gbs > 0.0);
    assert!(
        ue8m0_decode(split.scales[0]).is_finite(),
        "the scale bytes are ue8m0 codes, not raw exponents"
    );
}
/// The fold's worst case, on terms built to expose it: one dominant block and 159 tiny ones.
///
/// The serial chain adds the dominant term first and then absorbs 159 terms each ~5e-7 of it, so
/// their low bits are lost; the split-K schedule sums twenty terms per shard before the butterfly
/// meets the dominant shard, so it keeps more of them. This is the shape of reassociation D51
/// permits, and the point of the declared tolerance: the difference is bounded and recorded, and
/// this test states its size on the worst input the operands allow rather than only on random
/// ones. It also pins that the two folds differ (a "tolerance" test on identical arms would assert
/// nothing).
#[test]
fn the_folds_differ_most_on_a_dominant_term_and_the_difference_is_bounded() {
    let mut terms = [0.0f32; splitk::K_BLOCKS];
    // Block 0 dominant: the largest E2M1 code (6) and the largest scales the arm generates.
    terms[0] = 6.0 * 6.0 * 32.0 * ue8m0_decode(131) * ue8m0_decode(129);
    // Blocks 1..159 tiny: the smallest positive E2M1 code (0.5) at the smallest scales.
    for term in terms.iter_mut().skip(1) {
        *term = 0.5 * 0.5 * 32.0 * ue8m0_decode(118) * ue8m0_decode(120);
    }
    let serial = splitk::serial_fold(&terms);
    let split = splitk::splitk_fold(&terms);
    assert_ne!(serial.to_bits(), split.to_bits());
    let relative = (f64::from(split) - f64::from(serial)).abs() / f64::from(serial).abs();
    println!(
        "fold_worst_case: dominant_term={:.6e} tiny_term={:.6e} serial={:.9e} splitk={:.9e} \
         relative_difference={relative:.3e}",
        terms[0], terms[1], serial, split
    );
    assert!(
        relative < splitk::DECLARED_TOLERANCE.f32_max_rel,
        "the worst-case fold difference {relative:.3e} must stay inside the declared f32 bound"
    );
    // The split-K shards each keep their own sum, so the tiny terms survive there.
    assert!(split != 0.0 && serial != 0.0);
}
