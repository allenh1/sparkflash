//! The shape defines kernels/instances.toml gave each compile group, generated by build.rs.
//!
//! Each constant is a text table of `#define SPARK_INSTANCE_<ENTRY>_<ARG> <value>u` lines, the
//! same defines the compiler received. The ABI modules extend their [crate::c_decl::Consts] with
//! the group they pin, so a test that reads `SPARK_ROUTER_HIDDEN` resolves it through the
//! instance list instead of a second hand-copied number.
include!(concat!(env!("OUT_DIR"), "/kernel_instance_defines.rs"));

/// The capacities `kernels/instances.toml` fixes for a compile group, generated by build.rs.
///
/// `OPT_MOE_SM121_PLAN_ROWS` is the dedup plan's rows table and `OPT_SELECT_SM121_SCORE_BLOCKS`
/// the batched score launch's block cap; a launch reads the entry's value instead of spelling
/// the number again in Rust.
pub mod capacities {
    include!(concat!(env!("OUT_DIR"), "/kernel_instance_capacities.rs"));
}

/// Parses a source and adds the generated defines of the released compile group that builds it.
///
/// A converted source takes its model geometry from `kernels/instances.toml`, so its static
/// asserts name entry-prefixed instance macros. The ABI tests resolve those through this table,
/// which is the same define table the compiler received for the released cubin.
#[must_use]
pub fn consts_for_source(source: &str, name: &str) -> crate::c_decl::Consts {
    let mut table = crate::c_decl::Consts::parse(source);
    match name {
        "b12x_mxfp4_moe_sm121.cu" => table.extend(B12X_MXFP4_MOE_SM121_DEFINES),
        "b12x_mxfp4_moe_stored_sm121.cu" => {
            table.extend(B12X_MXFP4_MOE_STORED_SM121_DEFINES);
        }
        "b12x_mxfp8_wo_a_sm121.cu" => table.extend(B12X_MXFP8_WO_A_SM121_DEFINES),
        _ => {}
    }
    table
}
