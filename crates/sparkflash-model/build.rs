//! Embed every shipped layout, so adding one is a data change.

use std::path::Path;

fn main() {
    let manifest = std::env::var("CARGO_MANIFEST_DIR").expect("a manifest directory");
    let directory = Path::new(&manifest).join("../../models/layouts");
    println!("cargo:rerun-if-changed={}", directory.display());
    let mut files = Vec::new();
    let entries = std::fs::read_dir(&directory).unwrap_or_else(|error| {
        panic!(
            "models/layouts at {} must be readable: {error}",
            directory.display()
        )
    });
    for entry in entries.flatten() {
        let path = entry.path();
        if path
            .extension()
            .is_some_and(|extension| extension == "toml")
        {
            files.push(path);
        }
    }
    files.sort();
    let mut generated = String::from(
        "// Generated by build.rs: every *.toml under models/layouts, embedded at build.\n         /// Every shipped layout: its file name and its text, in file-name order.\n         pub const SHIPPED: &[(&str, &str)] = &[\n",
    );
    for file in files {
        println!("cargo:rerun-if-changed={}", file.display());
        let name = file
            .file_name()
            .and_then(std::ffi::OsStr::to_str)
            .expect("a UTF-8 layout file name");
        generated.push_str(&format!(
            "    ({name:?}, include_str!({:?})),\n",
            file.display().to_string()
        ));
    }
    generated.push_str("];\n");
    let out = std::env::var("OUT_DIR").expect("an output directory");
    std::fs::write(Path::new(&out).join("layouts.rs"), generated)
        .expect("write the embedded layout list");
}
