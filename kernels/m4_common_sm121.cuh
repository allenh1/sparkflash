// The MLA attention score scale: 1 / sqrt(512), the latent width that the score is a dot product
// over. Specification 2.3 states the sparse-selection rule but not this constant, so the
// convention is stated here once and consumed by the kernel, and src/mla_ref.rs carries the same
// literal, with a test that compares the two texts bit for bit. If the spec ever pins the scale,
// this define and the reference constant move together or the test fails.
#define SPARK_M4_MLA_SCORE_SCALE 0.04419417382415922f

// Query heads per indexer head: 64 query heads over 32 indexer heads (8 per rank, spec 2.1), so
// one indexer head serves two query heads and the two index spaces cannot share an index. The
// kernel divides by this ratio when it reads index_query.
#define SPARK_M4_MLA_HEADS_PER_INDEX_HEAD (SPARK_M4_HEADS / SPARK_M4_INDEX_HEADS)
static_assert(SPARK_M4_HEADS % SPARK_M4_INDEX_HEADS == 0u,
              "query heads must divide evenly into indexer heads");
static_assert(SPARK_M4_HEADS / SPARK_M4_INDEX_HEADS == 2u, "64 query heads over 32 indexer heads");

// Block-wide sum of one per-thread partial. The tree is a plain shared-memory reduction rather
// than warp shuffles so that the same source parses under the clang stub, and the partials are
// added in a fixed tree order, which is what makes the result reproducible: the caller passes
// exactly SPARK_M4_REDUCE_SLOTS threads. Only lane 0 returns a meaningful value, and the call is
// itself a block-wide rendezvous, so every thread of the block must reach it.
#define SPARK_M4_REDUCE_SLOTS 256u
__device__ __forceinline__ float spark_block_sum(float value, uint32_t lane, uint32_t threads) {
    __shared__ float s_partial[SPARK_M4_REDUCE_SLOTS];
    s_partial[lane] = value;
    __syncthreads();
    for (uint32_t stride = threads / 2u; stride > 0u; stride >>= 1u) {
        if (lane < stride) {
            s_partial[lane] += s_partial[lane + stride];
        }
        __syncthreads();
    }
    return s_partial[0];
}

// Block-wide maximum of one per-thread partial, with the same fixed tree order as spark_block_sum
// and the same contract: the caller passes exactly SPARK_M4_REDUCE_SLOTS threads, only lane 0
// returns a meaningful value, and the call is a rendezvous that every thread of the block must
// reach. A maximum must NOT be accumulated with a shared-memory read-modify-write from every
// thread: that is a data race whose lost updates can leave the result below the true maximum, and
// a softmax that subtracts too small a maximum overflows to infinity. The tree has no race and
// the same result every run, which is what lets a CPU reference pin it.
__device__ __forceinline__ float spark_block_max(float value, uint32_t lane, uint32_t threads) {
    __shared__ float s_max_partial[SPARK_M4_REDUCE_SLOTS];
    s_max_partial[lane] = value;
    __syncthreads();
    for (uint32_t stride = threads / 2u; stride > 0u; stride >>= 1u) {
        if (lane < stride) {
            const float other = s_max_partial[lane + stride];
            s_max_partial[lane] = other > s_max_partial[lane] ? other : s_max_partial[lane];
        }
        __syncthreads();
    }
    return s_max_partial[0];
}
