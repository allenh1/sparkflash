// kernels/m4_common_sm121.cuh
//
// Shared constants, dtype codecs and geometry asserts of the Milestone 4 sm_121a kernels
// (specification section 6.2, line 1337, with the architecture in 2.1-2.4).
//
// Six kernels include this header: mega_mhc_sm121.cu, b12x_mxfp8_dense_sm121.cu,
// b12x_mxfp4_moe_sm121.cu, flash_mla_csa2_sm121.cu, b12x_mxfp8_wo_a_sm121.cu and
// cert_lm_head_sm121.cu. The Rust mirror lives in crates/sparkflash-kernels/src/m4_abi.rs,
// which parses the DECLARATIONS in this file and in each kernel and re-derives every geometry
// number instead of restating a Rust constant.
//
// Numerical contract. The MX block formats are stored as plain bytes in this project:
//   * FP8 E4M3 activations/weights: one uint8_t per element, the E4M3 bit pattern;
//   * FP4 E2M1 weights and Main KV: two nibbles per uint8_t, low nibble first;
//   * ue8m0 block scales: one uint8_t exponent per block, value = 2^(bits - 127).
// Storing them as uint8_t rather than __nv_fp8_e4m3/__nv_fp4_e2m1 keeps the ABI independent of
// CUDA's wrappers (whose members are protected and whose names move between minor releases),
// keeps sizeof/alignof trivially assertable, and lets the CPU reference reproduce the codec
// bit for bit. A consumer that wants the CUDA types can reinterpret the buffers: the layouts
// are identical.
//
// The encoders below take CUDA's own conversion intrinsic when the real toolkit is compiling
// (nvcc), because that is the code the GPU would execute. On the clang syntax-only probe the
// same functions fall back to explicit bit arithmetic. The two must agree, and that agreement
// is not assumed: crates/sparkflash-kernels/tests/m4_codec_golden.rs checks the Rust mirror of
// the bit arithmetic against a table generated by nvcc 12.9.1 calling __nv_cvt_float_to_fp8 and
// __nv_cvt_float_to_fp4 for every value this pipeline can present.
#pragma once

