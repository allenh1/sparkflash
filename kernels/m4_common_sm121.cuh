// A fused kernel that needs a whole-grid reduction (Mega-mHC's RMS pre-norm) synchronises
// through coherent memory. Spinning forever would let one wedged block hang the graph, so every
// wait is bounded by a %globaltimer deadline and reports a timeout instead. Both knobs are
// compile-time overridable, and the Rust mirror parses the defaults out of this file.
#ifndef SPARK_M4_SYNC_TIMEOUT_NS
#define SPARK_M4_SYNC_TIMEOUT_NS 200000ull
#endif
#ifndef SPARK_M4_SYNC_SPIN_SLEEP_NS
#define SPARK_M4_SYNC_SPIN_SLEEP_NS 200u
#endif
#define SPARK_M4_SYNC_SPINS_PER_SLEEP 64u

// Waits until *flag becomes non-zero or the deadline passes. Returns 1 when the flag was
// observed set and 0 on timeout; the caller decides what a timeout means, and in these kernels
// it means "produce the NaN-filled output and a diagnostic trace record".
__device__ __forceinline__ uint32_t spark_wait_for_flag(const volatile uint32_t *flag,
                                                       uint64_t deadline) {
    uint32_t spins = 0u;
    while (*flag == 0u) {
        if (spark_read_globaltimer_ns() >= deadline) {
            return 0u;
        }
        if (++spins >= (uint32_t)SPARK_M4_SYNC_SPINS_PER_SLEEP) {
            __nanosleep((unsigned int)SPARK_M4_SYNC_SPIN_SLEEP_NS);
            spins = 0u;
        }
    }
    return 1u;
}

// The OBSERVING side's poll: the same wait, with the acquire fence in the same expansion.
//
// Why a function rather than two lines at the call site. A release/acquire pair has two halves: the
// publisher stores the flag after its own __threadfence(), and the observer must not let the loads
// that read the published payload float above its observation of the flag. Written out at the call
// site, that acquire is a property of the call site's SHAPE - of a fence being present there, of its
// not being inside an if, of a return not standing in front of it - so an edit to the caller can
// remove it and a reviewer has to re-derive the caller's control flow from scratch. In this function
// the fence is part of the expansion: a caller that names the helper gets the poll and the fence
// together, and losing the fence means replacing the call itself. Raw spark_wait_for_flag stays
// available for the publisher side, which needs the wait without an acquire.
//
// That is what this source states, and it is a statement about this file plus a check on the call
// sites - not about the compiler. Replacing the call is not hypothetical: a
// #define spark_wait_for_flag_acquire(f, d) (1u) in a kernel, a #define __threadfence() ((void)0)
// anywhere in the translation unit, or a second, better-matching overload of this name each delete
// the acquire without touching these three lines. The source-level guard in
// crates/sparkflash-kernels/src/m4_abi.rs therefore rejects, naming the file and the line: a bare
// spark_wait_for_flag call in a kernel translation unit; a #define of spark_wait_for_flag,
// spark_wait_for_flag_acquire or __threadfence in any source under kernels/; any second definition
// or overload of spark_wait_for_flag_acquire outside this header; and, inside this body, anything
// other than exactly one top-level poll followed by a top-level __threadfence(). It reads
// unpreprocessed text, so what it does not see is enumerated in that module's documentation and
// pinned there by tests. The acquire is real because the fence is here and because nvcc compiles
// this body into the observing kernel's PTX; the scan only keeps the shape from drifting.
//
// The fence is unconditional on BOTH paths, which is why it cannot live inside a branch. The wait
// returns 1 when the flag was observed and 0 on timeout; the acquire is needed on the observed path
// (it pairs with the publisher's release), and a timeout is exactly where it must not be skipped
// either, because the flag can be published just after the deadline was read and the caller may
// still go on to read the same buffers. A fence on one arm only would make the source's guarantee
// depend on which arm ran, and that is the one thing a reader cannot check from the call site.
__device__ __forceinline__ uint32_t spark_wait_for_flag_acquire(const volatile uint32_t *flag,
                                                              uint64_t deadline) {
    const uint32_t observed = spark_wait_for_flag(flag, deadline);
    __threadfence();
    return observed;
}

// bf16 quiet NaN for the diagnostic output paths, as in the M3 kernel.
__device__ __forceinline__ __nv_bfloat16 spark_diag_nan_bf16(void) {
    return __ushort_as_bfloat16((unsigned short)0x7fc0u);
}

// exp() and sqrt(), device side. Both are the accurate CUDA math functions (not the __expf
// approximation), because the Sinkhorn-Knopp result is part of the numerical contract the CPU
// reference defines; the stub in the clang probe provides declarations with no semantics.
__device__ __forceinline__ float spark_exp(float x) { return expf(x); }

__device__ __forceinline__ float spark_sqrt(float x) { return sqrtf(x); }

// ---------------------------------------------------------------------------------------
// Weight layouts, and they are two different formats. The checkpoint stores them differently and
// the loader has to know which is which (docs/architecture/03-moe.md:118-134):
//
//   * FP8 E4M3 dense weights (attention, gate, shared expert, engram.wkv, indexer): the scale is a
//     genuine 2-D block grid, [ceil(out/32), ceil(in/32)] with ONE ue8m0 scale per 32x32 block.
//     That is the B12x layout below. Kernel.py asserts exactly that shape.
//   * FP4 E2M1 routed-expert weights: the scale is [out, in/32], one scale per output row per 32
//     values along K, which is the spark_b12x_row_* helpers below. The two formats are NOT
//     interchangeable and do not even have the same scale count: the fp8 grid has
//     ceil(out/32) * in/32 scales for a matrix, the fp4 grid has out * in/32.
//
// The spec fixes the tile shape but not byte offsets, so the helpers below are the single
// definition of the B12x byte layout, every kernel indexes weights through them, and the Rust
// references mirror them value for value (tests/b12x_index_parity.rs compiles this block with a C
// compiler and compares it against the Rust twin for every element of several shapes).
// ---------------------------------------------------------------------------------------
#define SPARK_B12X_NTILE 32u
#define SPARK_B12X_KTILE 32u
#define SPARK_B12X_TILE_BYTES (SPARK_B12X_NTILE * SPARK_B12X_KTILE)

// SPARK_B12X_INDEX_HELPERS_BEGIN -- extracted verbatim by tests/b12x_index_parity.rs.
__device__ __forceinline__ uint64_t spark_b12x_weight_index(uint32_t n, uint32_t k, uint32_t inner) {
    const uint32_t k_blocks = inner / SPARK_B12X_KTILE;
    const uint64_t tile = (uint64_t)(n / SPARK_B12X_NTILE) * k_blocks + (k / SPARK_B12X_KTILE);
    return tile * SPARK_B12X_TILE_BYTES + (uint64_t)(n % SPARK_B12X_NTILE) * SPARK_B12X_KTILE +
           (k % SPARK_B12X_KTILE);
}

// One scale per 32x32 block: the same byte for every element of the block, which is what makes the
// scale count ceil(rows / 32) * (inner / 32) rather than one per row.
__device__ __forceinline__ uint64_t spark_b12x_scale_index(uint32_t n, uint32_t k, uint32_t inner) {
    const uint32_t k_blocks = inner / SPARK_B12X_KTILE;
    return (uint64_t)(n / SPARK_B12X_NTILE) * k_blocks + (k / SPARK_B12X_KTILE);
}

// The FP4 routed-expert scale layout: [out, in/32], one scale per output row per 32 along K.
__device__ __forceinline__ uint64_t spark_b12x_row_scale_index(uint32_t n, uint32_t k, uint32_t inner) {
    return (uint64_t)n * (inner / SPARK_B12X_KTILE) + (k / SPARK_B12X_KTILE);
}

// Rows of a B12x buffer rounded up to whole micro-tile rows: the layout addresses whole 32-row
// tiles, so a matrix whose row count is not a multiple of 32 needs the padded allocation.
__device__ __forceinline__ uint64_t spark_b12x_padded_rows(uint32_t rows) {
    return ((uint64_t)rows + SPARK_B12X_NTILE - 1u) / SPARK_B12X_NTILE * SPARK_B12X_NTILE;
}

// Weight bytes a B12x buffer of the given shape occupies, INCLUDING the padding of the last
// micro-tile row. A caller that allocated rows * inner would have the tail of that tile written
// past the end, so the safe size is this one and there is no unpadded variant to confuse it with.
__device__ __forceinline__ uint64_t spark_b12x_buffer_bytes(uint32_t rows, uint32_t inner) {
    return spark_b12x_padded_rows(rows) * inner;
}

// ue8m0 scale bytes for the same buffer: one per 32x32 block, i.e. exactly ceil(rows/32) *
// ceil(inner/32). This is a SEPARATE size from the weight bytes and a group stride for scales must
// use it: using the weight size instead walks off the end of the scale buffer for every group
// after the first.
__device__ __forceinline__ uint64_t spark_b12x_scale_bytes(uint32_t rows, uint32_t inner) {
    return (spark_b12x_padded_rows(rows) / SPARK_B12X_NTILE) * (inner / SPARK_B12X_KTILE);
}

// The FP4 expert scale bytes: out * in/32, the row-major count of the fp4 grid.
__device__ __forceinline__ uint64_t spark_b12x_row_scale_bytes(uint32_t rows, uint32_t inner) {
    return (uint64_t)rows * (inner / SPARK_B12X_KTILE);
}
