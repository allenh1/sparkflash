// uint32_t bit view of a float, shared by the kernels and the Rust mirror. CUDA's own
// __float_as_uint/__uint_as_float are used rather than type punning, because that is the idiom
// both toolchains accept in device code.
__device__ __forceinline__ uint32_t spark_float_bits(float value) {
    return __float_as_uint(value);
}

__device__ __forceinline__ float spark_bits_float(uint32_t bits) {
    return __uint_as_float(bits);
}

// The E4M3 bit pattern of a float, round-to-nearest-even, saturating to +-448 (0x7E/0xFE).
// OCP MX E4M3 element format: sign, 4 exponent bits (bias 7), 3 mantissa bits, subnormals in
// man * 2^-9, 0x7F/0xFF reserved as NaN.
__device__ __forceinline__ uint8_t spark_fp8_e4m3_encode_fallback(float value) {
    const uint32_t bits = spark_float_bits(value);
    const uint32_t sign = (bits >> 31) & 1u;
    const uint32_t exponent = (bits >> 23) & 0xFFu;
    const uint32_t mantissa = bits & 0x7FFFFFu;
    const uint8_t sign_byte = (uint8_t)(sign << 7);
    const uint32_t magnitude = bits & 0x7FFFFFFFu;

    if (magnitude < 0x00800000u) {
        // Zero, and float subnormals rounding to the E4M3 subnormal step of 2^-9.
        // Ties at exactly 2^-10 round to the even code, which is zero.
        return (uint8_t)(sign_byte | (spark_bits_float(magnitude) > 0.0009765625f ? 1u : 0u));
    }
    if (exponent == 0xFFu) {
        // NaN keeps a quiet pattern; +-Inf saturates to the largest magnitude.
        return (uint8_t)(mantissa != 0u ? 0x7Fu : (uint8_t)(sign_byte | 0x7Eu));
    }

    const uint32_t significand = 0x00800000u | mantissa;
    const int32_t unbiased = (int32_t)exponent - 127;

    // The subnormal range is handled first, from the unrounded significand. E4M3's subnormal
    // step is 2^-9 and the float significand is 24 bits with an implied leading one, so the code
    // is round(significand / 2^(14 - unbiased)). Doing this before the normal-path mantissa carry
    // matters: a value that rounds up to 2^-6 is a tie at the subnormal boundary, and deriving it
    // from the carried exponent instead would round it a full step too high. The shift stays
    // below 32, because a 32-bit shift by 32 or more is undefined in C and on the GPU silently
    // uses only the low five bits of the shift amount; beyond shift 31 the value is far below
    // half a subnormal step and rounds to zero.
    if (unbiased < -6) {
        const int32_t shift = 14 - unbiased;
        if (shift >= 32) {
            return sign_byte;
        }
        const uint32_t code = significand >> shift;
        const uint32_t tail = significand & ((1u << shift) - 1u);
        const uint32_t half = 1u << (shift - 1u);
        uint32_t rounded = code;
        if (tail > half || (tail == half && (rounded & 1u) != 0u)) {
            rounded += 1u;
        }
        if (rounded >= 8u) {
            return (uint8_t)(sign_byte | 0x08u); // 2^-6, the smallest normal
        }
        return (uint8_t)(sign_byte | (uint8_t)rounded);
    }

    // Normal range: E4M3 keeps three of the 23 mantissa bits, so the rounding point is bit 20 of
    // the 24-bit significand.
    uint32_t kept = significand >> 20;
    const uint32_t remainder = significand & 0x000FFFFFu;
    int32_t exponent_value = unbiased;
    if (remainder > 0x00080000u || (remainder == 0x00080000u && (kept & 1u) != 0u)) {
        kept += 1u;
    }
    if (kept == 16u) {
        kept = 8u;
        exponent_value += 1;
    }
    // Saturation. Exponent field 15 with mantissa field 7 is the E4M3 NaN, so a value that
    // rounds up to 1.875 * 2^8 (= 480) has nowhere to go and must saturate to 448 instead of
    // producing the NaN code: CUDA's saturating converter does exactly that. Two numbers, counted
    // by enumerating all 65,536 bf16 inputs rather than reasoned about: the code 0x7E is first
    // PRODUCED at 432, by ordinary rounding up to the format maximum (the bf16 input below it, 430,
    // still gives 0x7D), and this saturation branch is first REACHED by an input just above 464.
    // bf16 spacing is 2 in that binade, so 464 and 466 are the neighbouring bf16 inputs and 465 is
    // an f32 input rather than a bf16 value. tests/m4_codec_golden.rs pins both boundaries.
    if (exponent_value > 8 || (exponent_value == 8 && kept == 15u)) {
        return (uint8_t)(sign_byte | 0x7Eu); // +-448, the largest E4M3 magnitude
    }
    // E4M3's exponent bias is 7: field 1 is 2^-6 and field 15 is 2^8.
    const uint32_t exponent_field = (uint32_t)(exponent_value + 7);
    const uint32_t mantissa_field = kept - 8u;
    return (uint8_t)(sign_byte | (uint8_t)(exponent_field << 3) | (uint8_t)mantissa_field);
}

// The E2M1 nibble of a float, round-to-nearest-even, saturating to +-6: sign, 2 exponent bits
// (bias 1), 1 mantissa bit; 0 and 0.5 are the only subnormals.
__device__ __forceinline__ uint8_t spark_fp4_e2m1_encode_fallback(float value) {
    const uint32_t bits = spark_float_bits(value);
    const uint32_t sign = (bits >> 31) & 1u;
    const uint32_t exponent = (bits >> 23) & 0xFFu;
    const uint32_t mantissa = bits & 0x7FFFFFu;
    const uint8_t sign_nibble = (uint8_t)(sign << 3);
    const uint32_t magnitude = bits & 0x7FFFFFFFu;

    if (magnitude < 0x00800000u) {
        // Only values at or above 0.25 round up to the 0.5 subnormal.
        // Ties at exactly 0.25 round to the even code, which is zero.
        return (uint8_t)(sign_nibble | (spark_bits_float(magnitude) > 0.25f ? 1u : 0u));
    }
    if (exponent == 0xFFu) {
        // E2M1 has no NaN code: the largest magnitude, 6.0, is the all-ones-exponent code 0x7.
        // CUDA documents that a NaN input gives positive MAXNORM whatever its sign, while an
        // infinity keeps its sign; the golden table records both, including -NaN -> 0x7.
        return (uint8_t)(mantissa != 0u ? 0x7u : (uint8_t)(sign_nibble | 0x7u));
    }
    const uint32_t significand = 0x00800000u | mantissa;
    const int32_t unbiased = (int32_t)exponent - 127;

    // Subnormals first, for the same reason as in the E4M3 encoder: E2M1's subnormal step is
    // 0.5, so the code is round(significand / 2^(22 - unbiased)) and the shift stays below 32.
    // The bias is 1, so the subnormal range is unbiased < 0: 0.5 is the code 0x1, not a normal,
    // and the smallest normal is 1.0 (exponent field 1).
    if (unbiased < 0) {
        const int32_t shift = 22 - unbiased;
        if (shift >= 32) {
            return sign_nibble;
        }
        const uint32_t code = significand >> shift;
        const uint32_t tail = significand & ((1u << shift) - 1u);
        const uint32_t half = 1u << (shift - 1u);
        uint32_t rounded = code;
        if (tail > half || (tail == half && (rounded & 1u) != 0u)) {
            rounded += 1u;
        }
        if (rounded >= 2u) {
            return (uint8_t)(sign_nibble | 0x2u); // 1.0
        }
        return (uint8_t)(sign_nibble | (uint8_t)rounded);
    }

    // Normal range: E2M1 keeps one mantissa bit, so the rounding point is bit 22.
    uint32_t kept = significand >> 22;
    const uint32_t remainder = significand & 0x003FFFFFu;
    int32_t exponent_value = unbiased;
    if (remainder > 0x00200000u || (remainder == 0x00200000u && (kept & 1u) != 0u)) {
        kept += 1u;
    }
    if (kept == 4u) {
        kept = 2u;
        exponent_value += 1;
    }
    if (exponent_value > 2) {
        return (uint8_t)(sign_nibble | 0x7u); // +-6, the E2M1 MAXNORM
    }
    const uint32_t exponent_field = (uint32_t)(exponent_value + 1);
    const uint32_t mantissa_field = kept - 2u;
    return (uint8_t)(sign_nibble | (uint8_t)(exponent_field << 1) | (uint8_t)mantissa_field);
}

