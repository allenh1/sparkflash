// Decoders are pure bit arithmetic on both toolchains, so the Rust reference reproduces them
// exactly. E4M3: subnormal step 2^-9, 0x7F/0xFF are NaN.
__device__ __forceinline__ float spark_fp8_e4m3_decode(uint8_t bits) {
    const float sign = (bits & 0x80u) != 0u ? -1.0f : 1.0f;
    const uint32_t exponent = (uint32_t)(bits >> 3) & 0x0Fu;
    const uint32_t mantissa = (uint32_t)bits & 0x07u;
    if (exponent == 0u) {
        return sign * (float)mantissa * 0.001953125f; // man * 2^-9
    }
    if (exponent == 15u && mantissa == 7u) {
        return spark_bits_float(0x7FC00000u); // quiet NaN, never produced by the encoder
    }
    const float power = spark_bits_float((exponent + 120u) << 23);
    return sign * power * (1.0f + (float)mantissa * 0.125f);
}

// E2M1: the sixteen codes are 0, 0.5, 1, 1.5, 2, 3, 4, 6 and their negatives.
__device__ __forceinline__ float spark_fp4_e2m1_decode(uint8_t nibble) {
    const float sign = (nibble & 0x8u) != 0u ? -1.0f : 1.0f;
    const uint32_t exponent = ((uint32_t)nibble >> 1) & 0x3u;
    const uint32_t mantissa = (uint32_t)nibble & 0x1u;
    if (exponent == 0u) {
        return sign * (float)mantissa * 0.5f;
    }
    const float power = spark_bits_float((exponent + 126u) << 23);
    return sign * power * (1.0f + (float)mantissa * 0.5f);
}

// ue8m0: value = 2^(bits - 127), 255 reserved. The encoder takes the block maximum and the
// element format's maximum exponent (8 for E4M3, 2 for E2M1) and returns
// 2^(floor(log2(amax)) - element_emax): the smallest power-of-two scale that keeps amax within
// the element format's range, which is the OCP MX shared-scale rule. The exponent is signed, so
// a block whose maximum is well below one still uses the element format's full mantissa
// precision instead of collapsing every element into a subnormal; the code is clamped to
// [0, 254], whose lower end is the smallest scale ue8m0 can express.
__device__ __forceinline__ uint8_t spark_ue8m0_from_amax(float amax, uint32_t element_emax) {
    if (!(amax > 0.0f)) {
        return (uint8_t)SPARK_M4_UE8M0_BIAS; // scale 1.0; a zero block encodes to all-zero codes
    }
    const uint32_t bits = spark_float_bits(amax);
    const uint32_t exponent_field = (bits >> 23) & 0xFFu;
    if (exponent_field == 0u) {
        return (uint8_t)SPARK_M4_UE8M0_BIAS; // a float subnormal is below any scale we emit
    }
    if (exponent_field == 0xFFu) {
        return (uint8_t)SPARK_M4_UE8M0_MAX; // an infinite block maximum takes the largest scale
    }
    int32_t exponent = (int32_t)exponent_field - 127 - (int32_t)element_emax;
    const int32_t ceiling = (int32_t)SPARK_M4_UE8M0_MAX - (int32_t)SPARK_M4_UE8M0_BIAS;
    const int32_t floor_code = -(int32_t)SPARK_M4_UE8M0_BIAS;
    if (exponent < floor_code) {
        exponent = floor_code;
    }
    if (exponent > ceiling) {
        exponent = ceiling;
    }
    return (uint8_t)(exponent + (int32_t)SPARK_M4_UE8M0_BIAS);
}

__device__ __forceinline__ float spark_ue8m0_decode(uint8_t bits) {
    if (bits == 255u) {
        return spark_bits_float(0x7FC00000u); // the reserved all-ones E8M0 pattern
    }
    if (bits == 0u) {
        // 2^-127 is not a normal float: as an f32 it is the subnormal with mantissa 2^22.
        return spark_bits_float(1u << 22);
    }
    return spark_bits_float((uint32_t)bits << 23);
}

// Quantize one row of count floats into dst with a shared ue8m0 scale per 32 values, emitting
// the scales into scales. count must be a multiple of 32. The encoder is RNE and saturating, so
// a code can never overflow.
__device__ __forceinline__ void spark_quantize_row_e4m3(const float *src, uint8_t *dst,
                                                       uint8_t *scales, uint32_t count) {
    const uint32_t blocks = count / SPARK_M4_QUANT_BLOCK;
    for (uint32_t b = 0; b < blocks; ++b) {
        const uint32_t base = b * SPARK_M4_QUANT_BLOCK;
        float amax = 0.0f;
        for (uint32_t i = 0; i < SPARK_M4_QUANT_BLOCK; ++i) {
            const float magnitude = src[base + i] < 0.0f ? -src[base + i] : src[base + i];
            amax = magnitude > amax ? magnitude : amax;
        }
        const uint8_t scale = spark_ue8m0_from_amax(amax, 8u);
        scales[b] = scale;
        const float inverse = 1.0f / spark_ue8m0_decode(scale);
        for (uint32_t i = 0; i < SPARK_M4_QUANT_BLOCK; ++i) {
            dst[base + i] = spark_fp8_e4m3_encode(src[base + i] * inverse);
        }
    }
}

// ---------------------------------------------------------------------------------------
// Sinkhorn-Knopp for H(X_l): 20 iterations of alternating row/column normalisation
// ---------------------------------------------------------------------------------------

// Normalises the n x n matrix m in place so that every row and column sums to one, using
// iterations alternating passes with an additive eps that keeps an all-zero row finite.
// Runs in shared memory in the Mega-mHC kernel; the CPU reference implements the same loop.
__device__ __forceinline__ void spark_sinkhorn_knopp(float m[SPARK_M4_HC_MULT][SPARK_M4_HC_MULT],
                                                    uint32_t iterations, float eps) {
    const uint32_t n = (uint32_t)SPARK_M4_HC_MULT;
    for (uint32_t it = 0; it < iterations; ++it) {
        for (uint32_t row = 0; row < n; ++row) {
            float sum = eps;
            for (uint32_t col = 0; col < n; ++col) {
                sum += m[row][col];
            }
            const float inverse = 1.0f / sum;
            for (uint32_t col = 0; col < n; ++col) {
                m[row][col] *= inverse;
            }
        }
        for (uint32_t col = 0; col < n; ++col) {
            float sum = eps;
            for (uint32_t row = 0; row < n; ++row) {
                sum += m[row][col];
            }
            const float inverse = 1.0f / sum;
            for (uint32_t row = 0; row < n; ++row) {
                m[row][col] *= inverse;
            }
        }
    }
}

